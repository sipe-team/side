const socialLabels: Record<SocialType, string> = {
  github: 'GitHub',
  linkedin: 'LinkedIn',
  instagram: 'Instagram',
  youtube: 'YouTube',
  kakao: 'KakaoTalk',
  email: 'Email',
  link: 'Link',
};

function normalizeUrl(url: string, type: SocialType): string {
  if (type === 'email') {
    return url.startsWith('mailto:') ? url : `mailto:${url}`;
  }
  if (/^https?:\/\//i.test(url)) return url;
  return `https://${url}`;
}

export interface SocialIconLinkProps extends Omit<ComponentProps<'a'>, 'href' | 'type'> {
  type: SocialType;
  url?: string;
  size?: SocialIconSize;
}

export function SocialIconLink({ type, url, size = 'sm', className, ...props }: SocialIconLinkProps) {
  const Icon = iconMap[type];
  const label = socialLabels[type];
  const iconClassName = cx(styles.icon, styles.size[size]);

  if (!url) {
    return <Icon className={iconClassName} role="img" aria-label={label} />;
  }

  return (
    <a
      className={cx(styles.link, className)}
      href={normalizeUrl(url, type)}
      target="_blank"
      rel="noopener noreferrer"
      aria-label={label}
      {...props}
    >
      <Icon className={iconClassName} role="img" aria-hidden="true" focusable="false" />
    </a>
  );
}
